"""One-off: point the Play listing's graphics section at the real artwork."""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
PATH = ROOT / "docs" / "store-listing.md"

OLD_START = "Generated by `tool/make_store_assets.py` from the committed brand source"
NEW_BLOCK = """Generated by `tool/make_store_assets.py` from the delivered brand artwork
(`assets/logo/weekend-logo.jpg`, matted to `assets/icons/weekend_logo.png` by
`tool/prepare_brand_assets.py`). The script scales the real pixels and composites
them onto the launcher background (`#0D0818`); it does not draw or approximate the
mark. Regenerate with:

```bash
python tool/make_store_assets.py
```
"""


def main() -> int:
    text = PATH.read_text(encoding="utf-8")
    start = text.index(OLD_START)
    # The old block ran to the end of the regenerating code fence.
    fence_end = text.index("```", text.index("```bash", start))
    fence_end = text.index("```", fence_end + 3) + 3
    text = text[:start] + NEW_BLOCK.rstrip("\n") + text[fence_end:]
    PATH.write_text(text, encoding="utf-8", newline="")
    print("store-listing.md updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
